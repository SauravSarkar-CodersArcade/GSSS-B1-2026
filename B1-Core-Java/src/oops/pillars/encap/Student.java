package oops.pillars.encap;
public class Student {
    private String name;
    private int rollNo;
    // setters
    public void setName(String name){
        this.name = name;
    }
    public void setRollNo(int rollNo){
        this.rollNo = rollNo;
    }
    // getters
    public String getName(){
        return this.name;
    }
    public int getRollNo(){
        return this.rollNo;
    }
}
